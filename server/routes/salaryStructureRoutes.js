import express from "express";
import { protect } from "../middleware/authMIddleware.js";
import { authorize } from "../middleware/roleMiddleware.js";
import { validate } from "../middleware/validate.js";
import { createSalaryStructure } from "../controllers/salaryStructure/createSalaryStructure.js";
import { getAllSalaryStructures } from "../controllers/salaryStructure/getAllSalaryStructures.js";
import { getSalaryStructureById } from "../controllers/salaryStructure/getSalaryStructureById.js";
import { updateSalaryStructure } from "../controllers/salaryStructure/updateSalaryStructure.js";
import { deleteSalaryStructure } from "../controllers/salaryStructure/deleteSalaryStructure.js";
import { restoreSalaryStructure } from "../controllers/salaryStructure/restoreSalaryStructure.js";
import { createSalaryStructureValidator } from "../validators/salaryStructureValidator.js";
const router = express.Router();
router.use(protect, authorize("Admin"));
router.post("/", createSalaryStructureValidator, validate, createSalaryStructure);
router.get("/", getAllSalaryStructures);
router.get("/:id", getSalaryStructureById);
router.put("/:id", createSalaryStructureValidator, validate, updateSalaryStructure);
router.delete("/:id", deleteSalaryStructure);
router.patch("/:id/restore", restoreSalaryStructure);
export default router;