import express from "express";
import { protect } from "../middleware/authMIddleware.js";
import { authorize } from "../middleware/roleMiddleware.js";
import { createAttendance, updateAttendance, getAllAttendance, deleteAttendance, myAttendance } from "../controllers/attendance/handlers.js";
const router = express.Router();
router.use(protect);
router.get("/me", authorize("Student"), myAttendance);
router.get("/", authorize("Admin", "Teacher"), getAllAttendance);
router.get("/:id", authorize("Admin", "Teacher"), getAllAttendance);
router.post("/", authorize("Admin", "Teacher"), createAttendance);
router.put("/:id", authorize("Admin", "Teacher"), updateAttendance);
router.delete("/:id", authorize("Admin"), deleteAttendance);
export default router;