import express from "express";
import { protect } from "../middleware/authMIddleware.js";
import { authorize } from "../middleware/roleMiddleware.js";
import { validate } from "../middleware/validate.js";
import { createFeeStructure } from "../controllers/feeStructure/createFeeStructure.js";
import { getAllFeeStructures } from "../controllers/feeStructure/getAllFeeStructures.js";
import { getFeeStructureById } from "../controllers/feeStructure/getFeeStructureById.js";
import { updateFeeStructure } from "../controllers/feeStructure/updateFeeStructure.js";
import { deleteFeeStructure } from "../controllers/feeStructure/deleteFeeStructure.js";
import { restoreFeeStructure } from "../controllers/feeStructure/restoreFeeStructure.js";
import { createFeeStructureValidator } from "../validators/feeStructureValidator.js";
const router = express.Router();
router.use(protect, authorize("Admin"));
router.post("/", createFeeStructureValidator, validate, createFeeStructure);
router.get("/", getAllFeeStructures);
router.get("/:id", getFeeStructureById);
router.put("/:id", createFeeStructureValidator, validate, updateFeeStructure);
router.delete("/:id", deleteFeeStructure);
router.patch("/:id/restore", restoreFeeStructure);
export default router;